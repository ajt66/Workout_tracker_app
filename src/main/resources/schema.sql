CREATE SCHEMA IF NOT EXISTS workoutapp;

-- PostgreSQL enum types (create if not exists)
CREATE TYPE IF NOT EXISTS workoutapp.exercise_type AS ENUM ('isolation', 'compound');
CREATE TYPE IF NOT EXISTS workoutapp.category_type AS ENUM ('cardio', 'strength', 'flexibility', 'hypertrophyorstrength', 'hypertrophy', 'isometrics');
CREATE TYPE IF NOT EXISTS workoutapp.log_status AS ENUM ('pending', 'completed', 'cancelled');
CREATE TYPE IF NOT EXISTS workoutapp.program_tag AS ENUM (
    'push', 'pull', 'legs', 'full_body', 'upper', 'lower', 'bro_split', 'rest', 'chest', 'arms', 'back', 'shoulders', 'cardio', 'core', 'stretching', 'none'
);
CREATE TYPE IF NOT EXISTS workoutapp.program_status AS ENUM ('active', 'inactive');

-- Users table
CREATE TABLE IF NOT EXISTS workoutapp.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(255) NOT NULL
);

-- Program table
CREATE TABLE IF NOT EXISTS workoutapp.program (
    program_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_name VARCHAR(50) NOT NULL,
    user_id BIGINT NOT NULL REFERENCES workoutapp.users(id),
    status workoutapp.program_status DEFAULT 'inactive' NOT NULL
);

-- Exercise list
CREATE TABLE IF NOT EXISTS workoutapp.exercise_list (
    user_id BIGINT NOT NULL REFERENCES workoutapp.users(id),
    exercise_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_name VARCHAR(50) NOT NULL UNIQUE,
    type workoutapp.exercise_type,
    muscle_group VARCHAR(50),
    category workoutapp.category_type NOT NULL
);

CREATE TABLE IF NOT EXISTS workoutapp.program_log (
    plog_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES workoutapp.programs(program_id),
    exercise_id BIGINT NOT NULL REFERENCES workoutapp.exercise_list(exercise_id),
    day VARCHAR(50) NOT NULL,
    sets INT,
    reps INT,
    duration VARCHAR(50),
    tag workoutapp.program_tag NOT NULL
);

-- Daily log
CREATE TABLE IF NOT EXISTS workoutapp.daily_log (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plog_id BIGINT NOT NULL REFERENCES workoutapp.program_log(plog_id),
    day VARCHAR(50) NOT NULL,
    logging_date DATE DEFAULT CURRENT_DATE NOT NULL,
    exercise_id BIGINT NOT NULL REFERENCES workoutapp.exercise_list(exercise_id),
    weights DECIMAL(10,2),
    sets INT,
    reps INT,
    duration VARCHAR(50),
    comment VARCHAR(50),
    status workoutapp.log_status DEFAULT 'pending' NOT NULL
);

