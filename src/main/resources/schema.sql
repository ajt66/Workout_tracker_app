-- PostgreSQL enum types (create if not exists)


-- Users table
CREATE TABLE IF NOT EXISTS workoutapp.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(200) NOT NULL,
    role VARCHAR(50) NOT NULL
);

-- Program table
CREATE TABLE IF NOT EXISTS workoutapp.programs (
    program_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_name VARCHAR(50) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES workoutapp.users(id),
    pstatus VARCHAR(50) DEFAULT 'inactive' NOT NULL
);

-- Exercise list
CREATE TABLE IF NOT EXISTS workoutapp.exercise_list (
    user_id BIGINT NOT NULL REFERENCES workoutapp.users(id),
    exercise_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_name VARCHAR(50) NOT NULL,
    etype VARCHAR(50),
    muscle_group VARCHAR(50),
    category VARCHAR(50) NOT NULL
);

CREATE TABLE IF NOT EXISTS workoutapp.program_log (
    plog_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES workoutapp.programs(program_id),
    exercise_id BIGINT NOT NULL REFERENCES workoutapp.exercise_list(exercise_id),
    day VARCHAR(50) NOT NULL,
    sets INT,
    reps INT,
    duration VARCHAR(50),
    tag VARCHAR(50) NOT NULL
);

-- Daily log
CREATE TABLE IF NOT EXISTS workoutapp.daily_log (
    log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id BIGINT NOT NULL REFERENCES workoutapp.programs(program_id),
    day VARCHAR(50) NOT NULL,
    logging_date DATE NOT NULL,
    exercise_id BIGINT REFERENCES workoutapp.exercise_list(exercise_id),
    weights INT,
    sets INT,
    reps INT,
    duration VARCHAR(50),
    comment VARCHAR(50),
    dstatus VARCHAR(50) DEFAULT 'pending' NOT NULL
);

