CREATE SCHEMA IF NOT EXISTS workoutapp;

CREATE TABLE IF NOT EXISTS User {
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    Username VARCHAR(50) NOT NULL UNIQUE,
    Email VARCHAR(255) NOT NULL UNIQUE,
    Password VARCHAR(255) NOT NULL,
    Role VARCHAR(255) NOT NULL,
    Created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
};

CREATE TABLE IF NOT EXISTS ExerciseList (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(50) NOT NULL UNIQUE,
    Type ENUM('ISOLATION', 'COMPOUND'),
    Muscle_Group VARCHAR(50),
    Category ENUM("CARDIO", "STRENGTH", "FLEXIBILTY","HYPERTROPHY","ISOMETRICS") NOT NULL
);

CREATE TABLE IF NOT EXISTS DailyLog {
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    Day VARCHAR(50) NOT NULL,
    Logging_Date DATE DEFAULT CURRENT_DATE,
    Exercise_ID BIGINT NOT NULL,
    Weights DECIMAL(10,2),
    Sets DECIMAL(10,2),
    Reps DECIMAL(10,2),
    Duration VARCHAR(50),
    Comment VARCHAR(50) NOT NULL,
    status ENUM('PENDING', 'COMPLETED', 'CANCELLED') DEFAULT 'PENDING'
    CONSTRAINT fk_exerciseList
    FOREIGN KEY (Exercise_ID) REFERENCES ExerciseList(id)
};